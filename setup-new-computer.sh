	eval "$(pyenv init -)"

	# Resolve the highest 3.x.y release (strips alpha/beta/rc/dev tags)
	LATEST_PYTHON=$(pyenv install --list | awk '/^[[:space:]]*3\.[0-9]+\.[0-9]+$/' | tail -1 | tr -d ' ')
