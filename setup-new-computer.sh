printHeading() {
	printf "\n\n\n\e[0;36m$1\e[0m \n"
}

printDivider() {
	printf %"$COLUMNS"s | tr " " "-"
	printf "\n"
}

printError() {
	printf "\n\e[1;31m"
	printf %"$COLUMNS"s | tr " " "-"
	if [ -z "$1" ]; then                              # Is parameter #1 zero length?
		printf "     There was an error ... somewhere\n" # no parameter passed.
	else
		printf "\n     Error Installing $1\n" # parameter passed.
	fi
	printf %"$COLUMNS"s | tr " " "-"
	printf " \e[0m\n"
}

printStep() {
	printf %"$COLUMNS"s | tr " " "-"
	printf "\nInstalling $1...\n"
	$2 || printError "$1"
}

