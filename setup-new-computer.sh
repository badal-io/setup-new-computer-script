getLastestNVM() {
	# From https://gist.github.com/lukechilds/a83e1d7127b78fef38c2914c4ececc3c
	# Get latest release from GitHub api | Get tag line | Pluck JSON value
	curl --silent "https://api.github.com/repos/nvm-sh/nvm/releases/latest" |
		grep '"tag_name":' |
		sed -E 's/.*"([^"]+)".*/\1/'
}
